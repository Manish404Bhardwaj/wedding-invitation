function formatICSDate(date) {
  const year = date.getUTCFullYear();
  const month = String(date.getUTCMonth() + 1).padStart(2, "0");
  const day = String(date.getUTCDate()).padStart(2, "0");
  const hour = String(date.getUTCHours()).padStart(2, "0");
  const minute = String(date.getUTCMinutes()).padStart(2, "0");
  const second = String(date.getUTCSeconds()).padStart(2, "0");
  return `${year}${month}${day}T${hour}${minute}${second}Z`;
}

function buildCalendarFile() {
  const start = new Date(weddingConfig.weddingDateTime);
  const end = new Date(start.getTime() + 3 * 60 * 60 * 1000);

  return [
    "BEGIN:VCALENDAR",
    "VERSION:2.0",
    "PRODID:-//Wedding Invitation//EN",
    "BEGIN:VEVENT",
    `UID:${Date.now()}@wedding-invitation`,
    `DTSTAMP:${formatICSDate(new Date())}`,
    `DTSTART:${formatICSDate(start)}`,
    `DTEND:${formatICSDate(end)}`,
    `SUMMARY:${weddingConfig.brideName} & ${weddingConfig.groomName} Wedding`,
    `DESCRIPTION:${weddingConfig.invitationMessage}`,
    `LOCATION:${weddingConfig.venueAddress}`,
    "END:VEVENT",
    "END:VCALENDAR"
  ].join("\r\n");
}

function downloadCalendar() {
  const icsContent = buildCalendarFile();
  const blob = new Blob([icsContent], { type: "text/calendar;charset=utf-8" });
  const fileUrl = URL.createObjectURL(blob);
  const link = document.createElement("a");
  link.href = fileUrl;
  link.download = "wedding-invitation.ics";
  document.body.appendChild(link);
  link.click();
  link.remove();
  URL.revokeObjectURL(fileUrl);
}

function openLightbox(src, alt) {
  elements.lightboxImage.src = src;
  elements.lightboxImage.alt = alt;
  elements.lightbox.classList.add("is-visible");
  elements.lightbox.setAttribute("aria-hidden", "false");
}

function closeLightbox() {
  elements.lightbox.classList.remove("is-visible");
  elements.lightbox.setAttribute("aria-hidden", "true");
}

function toggleMobileMenu() {
  const isOpen = elements.navMenu.classList.toggle("is-open");
  elements.navToggle.setAttribute("aria-expanded", String(isOpen));
}

function bindEvents() {
  elements.navToggle.addEventListener("click", toggleMobileMenu);

  elements.navMenu.querySelectorAll("a").forEach((link) => {
    link.addEventListener("click", () => {
      elements.navMenu.classList.remove("is-open");
      elements.navToggle.setAttribute("aria-expanded", "false");
    });
  });

  elements.openInvitation.addEventListener("click", async () => {
    document.body.classList.add("is-invitation-open");
    elements.splash.style.display = "none";

    const video = elements.storyVideo;
    if (video) {
      video.muted = false;
      video.volume = 1;
      video.currentTime = 0;
      try {
        await video.play();
      } catch (error) {
        console.warn("Video audio could not start on click:", error);
      }
    }
  });

  elements.downloadCalendar.addEventListener("click", downloadCalendar);
  elements.mapLink.addEventListener("click", (event) => {
    if (!weddingConfig.googleMapsLink) {
      event.preventDefault();
    }
  });

  elements.whatsappButton.href = buildWhatsAppLink();
  elements.lightbox.addEventListener("click", (event) => {
    if (event.target === elements.lightbox || event.target.closest(".lightbox-close")) {
      closeLightbox();
    }
  });

  document.addEventListener("keydown", (event) => {
    if (event.key === "Escape") {
      closeLightbox();
    }
  });

  window.addEventListener("scroll", updateParallax, { passive: true });
}

function initializePage() {
  setStaticText();
  renderInvitationSlides();
  renderEvents();
  renderGallery();
  renderFamilyCards();
  initCountdown();
  initRevealAnimations();
  bindEvents();
  createPetals();
  updateParallax();
  document.body.classList.add("is-ready");
}

initializePage();
