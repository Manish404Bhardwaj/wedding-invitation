function initRevealAnimations() {
  const revealItems = document.querySelectorAll(".reveal");

  if (prefersReducedMotion || !("IntersectionObserver" in window)) {
    revealItems.forEach((item) => item.classList.add("is-visible"));
    return;
  }

  const observer = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) {
          entry.target.classList.add("is-visible");
          observer.unobserve(entry.target);
        }
      });
    },
    { threshold: 0.15 }
  );

  revealItems.forEach((item) => observer.observe(item));
}

function createPetals() {
  const colors = [
    "linear-gradient(180deg, rgba(255,255,255,0.95), rgba(255, 212, 112, 0.92) 30%, rgba(232, 115, 122, 0.9) 70%, rgba(172, 102, 42, 0.8))",
    "linear-gradient(180deg, rgba(255,255,255,0.96), rgba(255, 184, 102, 0.92) 28%, rgba(250, 131, 82, 0.88) 70%, rgba(127, 58, 32, 0.8))",
    "linear-gradient(180deg, rgba(255,255,255,0.96), rgba(210, 129, 255, 0.9) 30%, rgba(111, 105, 255, 0.86) 72%, rgba(72, 52, 128, 0.8))",
    "linear-gradient(180deg, rgba(255,255,255,0.96), rgba(255, 224, 146, 0.92) 30%, rgba(202, 178, 91, 0.9) 70%, rgba(124, 83, 28, 0.82))"
  ];

  const petals = Array.from({ length: 24 }, (_, index) => {
    const petal = document.createElement("span");
    petal.className = "petal";
    petal.style.setProperty("--left", `${Math.random() * 100}%`);
    petal.style.setProperty("--duration", `${6 + Math.random() * 7}s`);
    petal.style.setProperty("--delay", `${(index * 0.28).toFixed(2)}s`);
    petal.style.background = colors[index % colors.length];
    petal.style.transform = `rotate(${Math.random() * 70 - 35}deg)`;
    petal.style.opacity = `${0.7 + Math.random() * 0.25}`;
    return petal;
  });

  petals.forEach((petal) => elements.petalLayer.appendChild(petal));
}

function updateParallax() {
  if (prefersReducedMotion) return;
  const offset = window.scrollY * 0.28;
  document.documentElement.style.setProperty("--hero-offset", `${offset}px`);
}

function initCountdown() {
  const timeNodes = {
    days: document.querySelector('[data-unit="days"]'),
    hours: document.querySelector('[data-unit="hours"]'),
    minutes: document.querySelector('[data-unit="minutes"]'),
    seconds: document.querySelector('[data-unit="seconds"]')
  };

  const update = () => {
    const now = new Date();
    let diff = countdownTarget - now;

    if (diff <= 0) {
      diff = 0;
    }

    const days = Math.floor(diff / (1000 * 60 * 60 * 24));
    const hours = Math.floor((diff / (1000 * 60 * 60)) % 24);
    const minutes = Math.floor((diff / (1000 * 60)) % 60);
    const seconds = Math.floor((diff / 1000) % 60);

    Object.entries({ days, hours, minutes, seconds }).forEach(([unit, value]) => {
      const valueNode = timeNodes[unit];
      const currentValue = valueNode.textContent.trim();
      const nextValue = String(value).padStart(2, "0");

      if (currentValue !== nextValue) {
        valueNode.textContent = nextValue;
        valueNode.parentElement.classList.remove("is-flipping");
        void valueNode.offsetWidth;
        valueNode.parentElement.classList.add("is-flipping");
        setTimeout(() => valueNode.parentElement.classList.remove("is-flipping"), 350);
      }
    });
  };

  update();
  setInterval(update, 1000);
}

